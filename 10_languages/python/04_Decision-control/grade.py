# if elif else
a=int(input("Enter the marks:"))

if a>90 :
  print("Grade is A")
elif(a>80 ):
  print("Grade is B")
elif(a>70 ):
  print("Grade is C")
elif(a>60 ):
  print("Grade is D")
elif(a>=50 ):
  print("Grade is E")
else:
  print("Grade is F")


